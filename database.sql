-- MajorMatch database (MySQL 5.7+ / MariaDB)
-- Import with:  mysql -u root -p < database.sql   (or use phpMyAdmin > Import)
CREATE DATABASE IF NOT EXISTS majormatch CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE majormatch;

DROP TABLE IF EXISTS user_exploration;
DROP TABLE IF EXISTS quiz_options;
DROP TABLE IF EXISTS quiz_questions;
DROP TABLE IF EXISTS experiences;
DROP TABLE IF EXISTS courses;
DROP TABLE IF EXISTS fields;
DROP TABLE IF EXISTS majors;

CREATE TABLE majors (
  id INT AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(5) NOT NULL UNIQUE,          -- cs / it / cy / ce (used in URLs)
  name_ar VARCHAR(100) NOT NULL,
  name_en VARCHAR(100) NOT NULL,
  description TEXT,
  icon VARCHAR(10)
);

CREATE TABLE fields (
  id INT AUTO_INCREMENT PRIMARY KEY,
  major_id INT NOT NULL,
  name VARCHAR(100) NOT NULL,
  description TEXT,
  category VARCHAR(20),                     -- profile dimension: ai, prog, web, sec, robo, hw, data, net
  FOREIGN KEY (major_id) REFERENCES majors(id) ON DELETE CASCADE
);

-- Course rows below are extracted from the uploaded Qassim University study-plan PDFs.
-- is_sample = 0 means these are source-based rows, not demo data.
CREATE TABLE courses (
  id INT AUTO_INCREMENT PRIMARY KEY,
  major_id INT NOT NULL,
  level TINYINT NOT NULL,                   -- 1 .. 8
  course_code VARCHAR(20) NOT NULL,
  course_name VARCHAR(150) NOT NULL,
  course_name_ar VARCHAR(150) NOT NULL,
  course_name_en VARCHAR(150) NOT NULL DEFAULT '',
  credit_hours TINYINT NOT NULL,
  prerequisite VARCHAR(100),
  is_sample TINYINT(1) NOT NULL DEFAULT 1,
  FOREIGN KEY (major_id) REFERENCES majors(id) ON DELETE CASCADE
);

CREATE TABLE experiences (
  id INT AUTO_INCREMENT PRIMARY KEY,
  major_id INT NOT NULL,
  field_id INT NOT NULL,
  title VARCHAR(150) NOT NULL,
  description TEXT,
  type VARCHAR(30) NOT NULL,                -- key used by js/experiences.js
  FOREIGN KEY (major_id) REFERENCES majors(id) ON DELETE CASCADE,
  FOREIGN KEY (field_id) REFERENCES fields(id) ON DELETE CASCADE
);

CREATE TABLE quiz_questions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  question VARCHAR(255) NOT NULL,
  category VARCHAR(30)
);

CREATE TABLE quiz_options (
  id INT AUTO_INCREMENT PRIMARY KEY,
  question_id INT NOT NULL,
  option_text VARCHAR(255) NOT NULL,
  major_id INT NOT NULL,                    -- main major that gets `score`
  score TINYINT NOT NULL,
  major2_id INT NULL,                       -- optional second major that gets `score2`
  score2 TINYINT NOT NULL DEFAULT 0,
  dim VARCHAR(20),                          -- interest dimension this answer supports
  FOREIGN KEY (question_id) REFERENCES quiz_questions(id) ON DELETE CASCADE,
  FOREIGN KEY (major_id) REFERENCES majors(id) ON DELETE CASCADE
);

CREATE TABLE user_exploration (
  id INT AUTO_INCREMENT PRIMARY KEY,
  session_id VARCHAR(64) NOT NULL,          -- anonymous visitor id (no login needed)
  experience_id INT NOT NULL,
  rating VARCHAR(10) NOT NULL,              -- love / ok / no
  score TINYINT NOT NULL,                   -- love = 2, ok = 1, no = 0
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (experience_id) REFERENCES experiences(id) ON DELETE CASCADE
);

